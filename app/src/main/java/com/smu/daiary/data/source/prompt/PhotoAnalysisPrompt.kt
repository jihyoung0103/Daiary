package com.smu.daiary.data.source.prompt

/**
 * 사진 1장에서 관찰 가능한 사실만 뽑아낸다.
 *
 * 항목은 "무엇이 찍혔나"(음식/장소/사물…)가 아니라 "일기에 어떻게 쓰이나"로 나눈다.
 * - 중심/주변: 문단의 주 소재와 곁들일 소재를 구분해 준다
 * - 글자: 자막·간판·영수증의 글자는 사진에서 가장 강한 단서라 따로 뽑는다
 * - 추측: 불확실한 정보를 격리해야 일기 모델이 사실로 승격시키지 않는다
 *
 * [diaryPrompt]와 "보이는 사실만 쓴다"는 원칙을 공유한다. 여기서 새는 추측은 그대로
 * 일기 본문의 사실이 되므로, 한쪽을 고칠 때 다른 쪽도 함께 봐야 한다.
 */
internal fun photoAnalysisPrompt(isCameraPhoto: Boolean): String {
    val kindRule = if (isCameraPhoto) {
        "이 사진은 카메라로 직접 촬영한 사진이야. 실제로 보이는 것을 그대로 적어."
    } else {
        "이 이미지는 화면 캡처(스크린샷)이거나 받은 이미지야. 화면에 담긴 내용만 적어. " +
                "사용자가 실제로 그 장소에 있었거나 무엇을 했다고 해석하지 마."
    }
    return """
사진에서 실제로 보이는 것만 정리해줘. 일기를 쓰지 말고 관찰만 하면 돼.

$kindRule

[규칙]
- "오늘은", "나는", "~했다" 같은 일기체 표현 금지.
- 감정, 의도, 이동 경로, 시간, 전후 맥락은 추측 금지.
- 집·학교·회사·외출·귀가 같은 생활 맥락은 단정하지 말 것.
- 확실하지 않은 것은 [추측]에만 적어. 나머지 항목에는 확실한 것만 적어.
- 마크다운 기호(**, *, #)를 쓰지 마. 순수 텍스트로만 작성.
- 아래 네 항목을 반드시 이 순서대로 모두 적어. 해당 없는 항목은 "없음"이라고 적어.
- 각 항목은 한 문장.

[출력 형식]
중심: 사진에서 가장 눈에 띄는 것 하나
주변: 배경이나 곁에 함께 보이는 것
글자: 온전히 읽히는 글자만 그대로 옮겨 적기
추측: 확실하지 않아 단정할 수 없는 것

[글자 항목 주의]
- 브랜드명·상호·간판처럼 이름에 해당하는 글자는 특히 조심해. 하류에서 그대로 사실로 쓰인다.
- 일부가 잘렸거나 가려졌거나 흐릿하면 [글자]에 적지 말고 [추측]에 적어.
  잘린 글자를 그럴듯하게 복원하지 마. 브랜드 이름은 비슷해 보여도 전혀 다른 가게일 수 있어.
  O: 글자: 없음 / 추측: 박스에 영문 브랜드명이 있으나 일부가 잘려 읽을 수 없다
  X: 글자: OLEW CHICKEN (박스 하단)      ← 실제로는 다른 가게일 수 있음
""".trimIndent()
}
