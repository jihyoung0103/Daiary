package com.smu.daiary.data.source.prompt

import com.smu.daiary.data.model.RetrospectType

/**
 * 일기 초안 외 프롬프트 모음. 사진 분석과 일기 본문은 "보이는 사실만 쓴다"는 같은 원칙을
 * 공유하므로, 한쪽만 고치고 다른 쪽을 놓치지 않도록 [diaryPrompt]와 가까이 둔다.
 */

/**
 * 대화의 첫 질문을 만든다.
 * 깊이는 후속 질문이 만든다. 첫 질문의 역할은 후속이 붙잡을 구체적인 사실 하나를 끌어내는 것이라,
 * 이유·감정은 일부러 묻지 않고 '구체화'에만 집중시킨다.
 */
internal fun contextQuestionsPrompt(blocksText: String): String = """
오늘 하루의 데이터 블럭을 보고 사용자에게 물어볼 질문을 만들어.
목표는 정보 수집이 아니라 대화의 첫 수야. 사용자가 답하면 그 답을 받아 한 번 더 물어볼 거야.
그러니 이유나 감정이 아니라, 이어서 물어볼 거리가 될 구체적인 사실을 끌어내.

[무엇을 묻나]
데이터에는 "무슨 일이 있었는지"만 있고 "그게 무엇이었는지"가 없어. 그 빈칸을 물어.
- 결제: 금액과 가맹점은 있지만 무엇을 샀는지 없음
- 일정: 제목과 시간은 있지만 무엇을 했고 어떻게 됐는지 없음
- 사진: 보이는 사물은 있지만 누구와 어디서인지 없음
- 건강: 걸음 수는 있지만 어디를 다녀왔는지 없음

[묻지 말 것]
- 답변을 들어도 일기 문장이 하나도 늘지 않는 질문. 이 기준으로 블럭을 걸러.
- 아직 일어나지 않은 일. 오늘 사용자가 겪은 일만 물어.
  내일 일정이나 예정된 계획은 답을 들어도 오늘 일기에 쓸 경험이 없어.
- 블럭 내용에 이미 답이 적혀 있는 것.
  X: 일정 제목이 "도미노피자 아르바이트"인데 "무슨 일정인가요?"라고 묻기
  물어서 알아낼 게 없으면 그 블럭은 건너뛰어.
- 예/아니오로 답이 끝나는 질문
- 한 번에 두 가지를 묻는 질문 (X: "어디서 누구와 드셨나요?")
- "어떠셨나요?", "좋으셨나요?" 같은 되묻기.
  사용자가 이미 아는 걸 요약하게 만들 뿐이고, 이어 물을 거리가 안 남아.

[어떻게 묻나]
- 데이터에 있는 사실을 질문 안에 넣어. 그래야 바로 떠올려서 답해.
  O: "14,200원은 무엇을 시키신 건가요?"
  X: "오늘 뭐 드셨나요?"
- 사실만 떠올리면 답할 수 있게. 이유와 감정은 다음 질문에서 물어볼 거야.
  O: "회의에서 어떤 이야기가 오갔나요?"
  X: "회의는 어떤 의미였나요?"
- 존댓말 한 문장.
- 사용자는 선택지 없이 직접 타이핑해서 답해. 50자 안에 답할 수 있는 질문만.

[개수]
- 한 블럭당 최대 1개.
- 전체 최대 3개. 답이 일기를 가장 크게 바꿀 블럭부터 골라.
- 물을 것이 없으면 0개도 괜찮아.

데이터 블럭:
$blocksText

반드시 아래 JSON 형식으로만 응답해. 다른 텍스트는 포함하지 마:
{
  "questions": [
    {
      "blockId": "블럭 id",
      "question": "질문 텍스트"
    }
  ]
}
""".trimIndent()

/**
 * 사진 1장에서 관찰 가능한 사실만 뽑아낸다.
 *
 * 항목은 "무엇이 찍혔나"(음식/장소/사물…)가 아니라 "일기에 어떻게 쓰이나"로 나눈다.
 * - 중심/주변: 문단의 주 소재와 곁들일 소재를 구분해 준다
 * - 글자: 자막·간판·영수증의 글자는 사진에서 가장 강한 단서라 따로 뽑는다
 * - 추측: 불확실한 정보를 격리해야 일기 모델이 사실로 승격시키지 않는다
 */
internal fun photoAnalysisPrompt(isCameraPhoto: Boolean): String {
    val kindRule = if (isCameraPhoto) {
        "이 사진은 카메라로 직접 촬영한 사진이야. 실제로 보이는 것을 그대로 적어."
    } else {
        "이 이미지는 화면 캡처(스크린샷)이거나 받은 이미지야. 화면에 담긴 내용만 적어. " +
            "사용자가 실제로 그 장소에 있었거나 무엇을 했다고 해석하지 마."
    }
    return """
사진에서 실제로 보이는 것만 정리해줘. 일기를 쓰지 말고 관찰만 하면 돼.

$kindRule

[규칙]
- "오늘은", "나는", "~했다" 같은 일기체 표현 금지.
- 감정, 의도, 이동 경로, 시간, 전후 맥락은 추측 금지.
- 집·학교·회사·외출·귀가 같은 생활 맥락은 단정하지 말 것.
- 확실하지 않은 것은 [추측]에만 적어. 나머지 항목에는 확실한 것만 적어.
- 마크다운 기호(**, *, #)를 쓰지 마. 순수 텍스트로만 작성.
- 아래 네 항목을 반드시 이 순서대로 모두 적어. 해당 없는 항목은 "없음"이라고 적어.
- 각 항목은 한 문장.

[출력 형식]
중심: 사진에서 가장 눈에 띄는 것 하나
주변: 배경이나 곁에 함께 보이는 것
글자: 자막·간판·라벨·화면 등에서 읽히는 글자를 그대로 옮겨 적기
추측: 확실하지 않아 단정할 수 없는 것
""".trimIndent()
}

/** 주간/월간 회고 — 내러티브 + 키워드 + 기억에 남는 하루를 1회 호출로 받는다. */
internal fun retrospectPrompt(
    type: RetrospectType,
    periodLabel: String,
    diarySummaries: String,
    emotionSummary: String,
    healthSummary: String,
    spendingSummary: String,
    scheduleSummary: String
): String {
    val periodInstruction = if (type == RetrospectType.WEEKLY) {
        "- 하루하루의 구체적 사건 언급 가능\n- 감정 흐름 변화 반영"
    } else {
        "- 한 달의 큰 흐름과 변화에 초점\n- 월초/월말 차이나 성장 반영\n- 세세한 하루 언급보다 전체 색채 표현"
    }

    return """
당신은 따뜻하고 공감 어린 시선을 가진 회고 작가입니다.
아래 사용자의 $periodLabel 데이터를 바탕으로 회고를 작성하세요.

[일기 목록 (날짜 · 감정 · 내용 일부)]
$diarySummaries

[감정 집계]
$emotionSummary

[건강 집계]
$healthSummary

[소비 집계]
$spendingSummary

[주요 일정]
$scheduleSummary

작성 규칙:
- narrative: 2~3문장, 1인칭 공감형, 과거형으로 작성
$periodInstruction
- keywords: 명사형 3~5개, 해시태그(#) 없이
- memorableDay: 위 일기 목록 중 하나의 날짜를 골라, 그 이유를 1~2문장으로 데이터 근거를 포함해서 작성
- 이모지 사용 금지
- JSON 외 텍스트 출력 금지

반드시 아래 JSON 형식으로만 응답하세요:
{
  "narrative": "...",
  "keywords": ["...", "..."],
  "memorableDay": { "date": "YYYY-MM-DD", "reason": "..." }
}
""".trimIndent()
}
