/**
 * 일기 초안 외 프롬프트 모음. 사진 분석과 일기 본문은 "보이는 사실만 쓴다"는 같은 원칙을
 * 공유하므로, 한쪽만 고치고 다른 쪽을 놓치지 않도록 [diaryPrompt]와 가까이 둔다.
 */

/**
 * 대화의 첫 질문을 만든다.
 * 깊이는 후속 질문이 만든다. 첫 질문의 역할은 후속이 붙잡을 구체적인 사실 하나를 끌어내는 것이라,
 * 이유·감정은 일부러 묻지 않고 '구체화'에만 집중시킨다.
 */
internal fun contextQuestionsPrompt(blocksText: String): String = """
오늘 하루의 데이터 블럭을 보고 사용자에게 물어볼 질문을 만들어.

일기는 사실을 나열하는 글이 아니야.
점심이 맛있었는지 다신 안 시킬 건지, 그 일정은 어땠는지,
누구와 무슨 얘기를 나눴는지 — 그날 느끼고 판단한 것이 일기의 알맹이야.
데이터에는 사실만 있으니 그 알맹이는 네 질문으로만 끌어낼 수 있어.

다만 감정부터 물으면 "그냥 좋았어"로 끝나. 사실이 깔려야 감정이 구체적으로 나와.
그래서 첫 질문은 대개 사실을 묻고, 그 답을 받아 한 번 더 물어 평가·감정으로 들어가.
사실은 목적지가 아니라 발판이야.

단, 블럭에 이미 사실이 충분히 있으면(사진 분석이 상세한 경우처럼)
첫 질문부터 평가나 감정을 물어도 돼. 후속 질문이 붙지 않고 끝날 수도 있으니,
그 블럭에서 한 번만 물을 수 있다면 무엇을 물어야 일기가 살아날지로 골라.

[무엇을 묻나]
데이터에는 "무슨 일이 있었는지"만 있고 "그게 무엇이었는지"가 없어. 그 빈칸을 물어.
- 결제: 금액과 가맹점은 있지만 무엇을 샀는지 없음
- 일정: 제목과 시간은 있지만 무엇을 했고 어떻게 됐는지 없음
- 사진: 보이는 사물은 있지만 누구와 어디서인지 없음
- 건강: 걸음 수는 있지만 어디를 다녀왔는지 없음

블럭 자체에는 물을 게 없어도, 그 블럭을 실마리 삼아 하루를 물을 수 있어.
답이 그 블럭에 대한 것이 아니라 사용자의 하루에 대한 것이면 물을 가치가 있어.

- 건강: 걸음 수는 이미 알아. 어디를 다녀왔는지는 모르니 그걸 물어.
  8,000보를 보통으로 놓고 그날이 많이 움직인 날인지 아닌지 먼저 판단해.
  많은 날과 적은 날은 하루의 모양이 달라서 물을 것도 달라져.
  적은 날 — 어디에 머물렀고 그 시간에 무엇을 했는지 물어.
    O: "1,419보로 많이 걷진 않으셨는데, 오늘은 어디서 시간을 보내셨나요?"
  많은 날 — 어디를 다녀왔는지 물어.
    O: "12,300보나 걸으셨는데 어디를 다녀오셨나요?"
  단, 걸음 수만으로 집에 있었다·외출했다를 단정하지 마. 차로 움직였을 수도 있어.
    X: "오늘은 집에만 계셨나 봐요, 뭐 하셨어요?"

- 날씨: 날씨에는 사실의 빈칸이 아예 없어. 기온·습도·도시 이름은 데이터가 이미 다 갖고 있고,
  그걸 일기에 적어봐야 사용자는 읽지도 않고 넘겨.
  날씨에서 데이터에 없는 건 단 하나, 그 날씨가 사용자에게 어떻게 작용했는가야.
  더워서 지쳤는지, 비 때문에 계획이 틀어졌는지 — 그건 본인만 알아. 그것만 물어.
  O: "32도 더위가 오늘 하루에 어떤 영향을 줬나요?"
  O: "흐린 날씨 속에서 오늘 기분은 어떻게 흘러갔나요?"
  X: "오늘 날씨는 어떠셨나요?"          (블럭에 이미 있는 내용을 되물음)
  X: "고양시는 날씨가 흐렸는데 어떠셨나요?"  (도시 이름은 사용자에게 아무 의미 없음)

단, 실마리로 쓸 때도 답을 미리 정해두지 마.
  O: "비 오는 하루를 어디서 보내셨나요?"
  X: "비가 와서 집에 계셨겠어요, 맞나요?"
  빗나가면 사용자가 해명부터 해야 하고, 그건 대화가 아니야.

- content가 "[화면 캡처/수신 이미지]"로 시작하는 사진은 화면에 무엇이 있는지가 분석에 이미 다 있어.
  구체화할 게 없으니 이런 사진은 "왜 이 화면을 남겼는지"를 물어. 그게 데이터에 없는 유일한 정보야.
  화면 속 내용을 다시 묻지 마.
  O: "이 화면은 어떤 순간이라 남겨두신 거예요?"
  O: "오늘 이 게임을 얼마나 하셨나요?"
  X: "보스 소환은 무엇인가요?"          (화면에 이미 적혀 있음)

블럭마다 묻는 것이 다르니 서로 중복될 걱정은 하지 마.
"다른 블럭에서 자연스럽게 나올 것 같다", "사진에 이미 보인다" 같은 이유로 블럭을 건너뛰지 마.
사용자가 그 얘기를 할지 안 할지는 알 수 없고, 안 하면 그 정보는 영영 없는 거야.

[묻지 말 것]
- 답변을 들어도 일기 문장이 하나도 늘지 않는 질문. 이 기준으로 블럭을 걸러.
- 아직 일어나지 않은 일. 오늘 사용자가 겪은 일만 물어.
  내일 일정이나 예정된 계획은 답을 들어도 오늘 일기에 쓸 경험이 없어.
- 블럭 내용에 이미 답이 적혀 있는 것.
  X: 일정 제목이 "도미노피자 아르바이트"인데 "무슨 일정인가요?"라고 묻기
  물어서 알아낼 게 없으면 그 블럭은 건너뛰어.
- 예/아니오로 답이 끝나는 질문. 대화가 거기서 멈춘다.
- 보기를 좁혀 주는 질문 (X: "집에서 드셨나요, 밖에서 드셨나요?")
- 한 번에 두 가지를 묻는 질문 (X: "어디서 누구와 드셨나요?")
- "어떠셨나요?", "좋으셨나요?" 같은 되묻기.
  사용자가 이미 아는 걸 요약하게 만들 뿐이고, 이어 물을 거리가 안 남아.

[어떻게 묻나]
- 반드시 열린 질문으로 물어. 사용자가 자유롭게 떠올려 답할 수 있어야 해.
  "무엇 / 어떤 / 어디서 / 어떻게 / 누구"로 묻으면 대개 열린 질문이 된다.
  "~인가요?", "~하셨나요?", "~맞나요?", "~있었어요?", "~있나요?"로 끝나면
  예/아니오로 닫히니 다시 써. "이유가 있었어요?"가 아니라 "이유가 뭐예요?"로 물어.
  O: "수육은 어디서 드신 건가요?"
  X: "수육은 점심때 봉구스밥버거에서 드신 건가요?"
- 한 질문은 한 블럭만 다뤄. 다른 블럭의 정보를 끌어와 섞지 마.
  블럭이 두 개면 같은 일인지 데이터로는 알 수 없다. 시간이 몇 시간씩 차이 날 수도 있다.
  X: 사진 블럭을 물으면서 결제 블럭의 가맹점 이름을 넣기
  같은 이유로 "다른 블럭에 이미 답이 있는 것 같다"며 블럭을 건너뛰지도 마.
  시각이 다르면 다른 일이고, 두 블럭이 같은 일이라는 근거는 어디에도 없어.
- 데이터에 있는 사실을 질문 안에 넣어. 그래야 바로 떠올려서 답해.
  단, 그 블럭 안에 있는 사실만. 하나면 충분하고 여러 개를 나열하지 마.
  O: "14,200원은 무엇을 시키신 건가요?"
  X: "오늘 뭐 드셨나요?"
  X: "17:15에 우아한형제들에서 24,000원은 무엇을 주문하신 건가요?"
- [추측]에 있는 내용은 질문에 사실처럼 넣지 마. 특히 가게·브랜드·음식 이름이 그래.
  대신 그 이름 자체를 물어. 사용자가 답해주면 그게 확실한 사실이 돼.
  O: "이 치킨은 어디서 시키신 건가요?"
  X: "올레 치킨은 어디서 시키신 건가요?"     (추측일 뿐인 이름을 단정)
  X: "저녁에 드신 보쌈은 어디서 드신 건가요?" (보쌈인지 아직 모름)
- 떠올리기 어려운 걸 묻지 마. 사실이든 느낌이든 바로 답할 수 있는 것만.
  O: "회의에서 어떤 이야기가 오갔나요?"
  X: "회의는 어떤 의미였나요?"          (곱씹어야 답이 나옴)
- 존댓말 한 문장.
- 사용자는 선택지 없이 직접 타이핑해서 답해. 50자 안에 답할 수 있는 질문만.

[개수]
- 한 블럭당 최대 1개.
- 전체 개수 제한은 없어. 물을 가치가 있는 블럭에는 전부 질문을 만들어.
  개수를 줄이려고 물을 만한 블럭을 임의로 빼지 마. 무엇을 답할지는 사용자가 고른다.
- 반대로 개수를 채우려고 억지 질문을 만들지도 마.
  위 [묻지 말 것]에 걸리는 블럭은 그냥 건너뛰어. 0개여도 괜찮아.

데이터 블럭:
$blocksText

반드시 아래 JSON 형식으로만 응답해. 다른 텍스트는 포함하지 마.
위 데이터 블럭의 모든 id는 questions와 skipped 중 정확히 한 곳에 들어가야 해.
질문을 만들지 않기로 한 블럭은 빠뜨리지 말고 skipped에 넣고, 왜 그렇게 판단했는지 짧게 적어.
reason은 30자 이내로 간결하게 써.
{
  "questions": [
    {
      "blockId": "블럭 id",
      "question": "질문 텍스트"
    }
  ],
  "skipped": [
    {
      "blockId": "블럭 id",
      "reason": "질문을 만들지 않은 이유"
    }
  ]
}
""".trimIndent()

/**
 * 미리 만들어 둔 질문을 그 사이 나온 답변에 맞춰 손본다.
 *
 * 첫 질문들은 대화가 시작되기 전에 한꺼번에 만들어지므로, 중간에 사용자가 답한 내용이
 * 반영돼 있지 않다. 그래서 이미 답이 나온 걸 또 묻거나, 답변 덕에 가능해진 더 좋은 질문을
 * 놓친다. 카드에 도착하는 시점에 이 프롬프트로 한 번 손본다.
 */
internal fun reviseQuestionPrompt(
    sourceId: String,
    sourceLabel: String,
    sourceContent: String,
    question: String,
    priorAnswers: String
): String = """
사용자와 하루에 대해 대화하는 중이야.
아래 질문은 대화를 시작하기 전에 미리 만들어 둔 거라, 그 사이 사용자가 한 답변이 반영돼 있지 않아.
지금까지의 답변을 보고 이 질문을 손봐줘.

[지금 손볼 소재]
$sourceLabel · $sourceId
$sourceContent

[미리 만들어 둔 질문]
$question

[지금까지 사용자가 답한 것]
소재별로 묶여 있어. 대괄호가 소재 구분이고, 한 묶음 안의 Q/A는 그 소재를 두고 이어간 대화야.
다른 소재에서 나온 답을 이 소재의 일과 같은 일로 여기지 마.

$priorAnswers

[어떻게 판단하나]
- 고칠 이유가 없으면 원래 질문을 그대로 돌려줘. 이게 기본이야. 멀쩡한 질문을 다듬지 마.
- 답변 덕분에 더 나은 질문이 가능해졌으면 그걸로 바꿔.
  예: 앞에서 "저녁을 못 먹었다"는 답이 나왔다면, 야식 사진은 그 사실을 이어받아 물을 수 있어.
- 이미 답이 나온 것을 묻고 있으면, 이 소재에서 아직 안 나온 것을 묻는 질문으로 바꿔.
- 이 소재에 대해 더 물을 것이 남아 있지 않으면 빈 문자열로 응답해. 그 카드는 건너뛴다.

[고칠 때 지켜야 할 것]
- 질문의 대상은 바꾸지 마. 반드시 [지금 손볼 소재]의 데이터를 묻는 질문이어야 해.
- 원래 질문에 그 소재의 사실(금액, 걸음 수, 시각 등)이 들어 있었다면 그대로 남겨.
  그게 사라지면 사용자는 무엇에 대한 질문인지 알 수 없게 돼.
  X: "2,993보로 많이 움직이지 않으셨는데 어디서 시간을 보내셨나요?"
     → "에어컨을 틀고 집에서 주로 뭘 하셨어요?"
     (걸음 수가 사라졌고, 날씨 답변을 그대로 옮겨와 날씨 질문과 같아짐)
- 다른 소재에서 이미 물은 것과 비슷해질 것 같으면, 고치지 말고 빈 문자열로 응답해.
  비슷한 질문을 두 번 하느니 그 카드를 건너뛰는 게 나아.

질문 작성 규칙은 원래와 같아.
- 열린 질문. "~인가요?", "~하셨나요?"로 끝나면 예/아니오로 닫히니 다시 써.
- 존댓말 한 문장, 50자 안에 답할 수 있게.
- 한 번에 두 가지를 묻지 마.
- 다른 소재의 정보를 이 질문에 끌어오지 마.

반드시 아래 JSON 형식으로만 응답해. 다른 텍스트는 포함하지 마:
{ "question": "질문 또는 빈 문자열" }
""".trimIndent()

/**
 * 방금 받은 답변을 근거로 한 걸음 더 들어가는 후속 질문을 만든다.
 *
 * 첫 질문이 '무엇'을 물어 구체적인 사실을 끌어냈다면, 후속은 그 사실을 붙잡고
 * '왜/어땠는지'로 들어간다. 데이터에 절대 남지 않는 정보가 여기서 나온다.
 * 더 물을 게 없으면 빈 문자열을 돌려받아 카드를 넘긴다.
 */
internal fun followUpQuestionPrompt(
    sourceContent: String,
    conversation: String
): String = """
사용자와 한 소재를 두고 대화하는 중이야. 지금까지 주고받은 걸 보고 한 번 더 물어봐.

첫 질문이 사실을 끌어냈으니, 이제 그 사실을 붙잡고 일기의 알맹이로 들어갈 차례야.
맛이 어땠는지, 왜 그랬는지, 누구와 있었는지, 그때 어떤 기분이었는지 —
데이터에는 절대 남지 않고 본인만 아는 것들이야. 그게 없으면 일기가 아니라 기록이 돼.

[원래 데이터]
$sourceContent

[지금까지 주고받은 것]
