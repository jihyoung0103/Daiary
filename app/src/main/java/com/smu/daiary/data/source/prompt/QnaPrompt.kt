  X: "오렌지색 굿즈를 입고 있는데 무슨 행사예요?"        (같은 질문을 돌려 물은 것)
  O: "다들 주황색으로 맞춰 입은 사람들 사이에 서 있으니 어땠어요?"
-------------------------------------------------------------------------------
[건너뛸 때]
아래에 해당하면 질문 대신 빈 문자열을 돌려줘. 그 카드는 건너뛴다.
- 이 소재로 물을 것이 앞선 답변에서 이미 다 나왔다.
- 답변을 들어도 일기 문장이 하나도 늘지 않는다.
- 소재 내용에 이미 답이 적혀 있다.
- 뒤에 올 소재가 같은 사건을 더 잘 다룰 수 있다.
빈손으로 넘기는 게 헛질문보다 나아. 억지로 만들지 마.
-------------------------------------------------------------------------------
[어떻게 묻나]
$QUESTION_RULES
- 이 소재 안의 사실을 하나만 질문에 넣어. 그래야 바로 떠올려서 답해.
  사진은 썸네일이 함께 보이니 굳이 넣지 않아도 무엇에 대한 질문인지 알아.
- 사진 분석은 유추일 뿐이야. "고기와 감자가 담긴 팬"이 사용자에겐 "엄마가 해준 백숙"이고
  그 이름은 사용자만 알아. 앞선 답변으로도 정체를 알 수 없으면 그걸 먼저 물어.
