  X: "정군족발"                      네 빈칸이 메워졌을 뿐 사용자는 얻은 게 없다
-------------------------------------------------------------------------------
[지금 물을 소재]
$sourceLabel
$sourceContent
-------------------------------------------------------------------------------
[오늘의 소재 전체]
이 중 하나가 위의 소재야. 뒤에 올 소재가 다룰 내용은 여기서 묻지 마.
$allSourcesText
-------------------------------------------------------------------------------
[지금까지 사용자가 답한 것]
${if (priorAnswers.isBlank()) "아직 없음 — 첫 카드다." else priorAnswers}

이미 나온 사실을 다시 묻지 마. 되묻는 순간 사용자는 "아까 말했잖아"가 되고,
그 카드는 아무것도 못 건지고 끝난다.

더 중요한 건 그 반대야. **이미 나온 사실을 딛고 한 단계 위에서 물어.**
정체를 아니까 정체 확인을 건너뛰고 곧장 느낌·이유·사람으로 들어갈 수 있어.
