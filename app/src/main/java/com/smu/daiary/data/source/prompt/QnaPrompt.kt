 */
internal fun contextQuestionsPrompt(blocksText: String): String = """
[가장 중요한 원칙]
일기를 쓰는 사람은 사용자야. 너는 쓰는 사람이 아니라 돕는 도구다.
네가 궁금한 걸 묻지 마. 사용자가 이미 알고 있지만 아직 말로 만들지 않은 것을
