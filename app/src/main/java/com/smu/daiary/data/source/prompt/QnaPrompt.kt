/**
 * 카드 한 장의 첫 질문을 만든다. 카드에 도착하기 직전에 한 장씩 호출한다.
 *
 * 이전에는 모든 카드의 첫 질문을 대화 시작 전에 한 번에 만들었다(contextQuestionsPrompt).
 * 그래서 질문이 답변을 못 봤다 — 걸음 수 카드에서 "바운디 콘서트에 갔다"는 답이 나온
 * 뒤에도 네 장 뒤 사진 카드가 "누구의 공연을 보셨어요?"를 물어 "바운디라고 몇번말하냐"를
 * 들었다.
 *
 * 잃는 것 없이 옮기려고 둘 다 넘긴다.
 *   allSourcesText — 앞으로 올 소재까지. 일괄 생성이 갖고 있던 정보로, 이게 있어야
 *                    "이건 뒤 사진에서 드러날 테니 건너뛴다" 같은 판단이 된다.
 *   priorAnswers   — 지금까지 나온 답. 중복을 피하는 것보다, 이미 아는 사실을 딛고
 *                    한 단계 위에서 물을 수 있게 되는 쪽이 더 크다.
 *
 * 제거된 reviseQuestionPrompt와 닮았지만 다르다. 그쪽은 멀쩡한 질문을 주고 "고쳐봐"라고
 * 불러서 손댈 이유가 없어도 손댔고, 자기 소재 하나만 봤다. 여기서는 처음부터 만든다.
 */
internal fun cardQuestionPrompt(
    sourceLabel: String,
    sourceContent: String,
    allSourcesText: String,
    priorAnswers: String
): String = """
[가장 중요한 원칙]
일기를 쓰는 사람은 사용자야. 너는 쓰는 사람이 아니라 돕는 도구다.
네가 궁금한 걸 묻지 마. 사용자가 이미 알고 있지만 아직 말로 만들지 않은 것을 꺼내도록 도와.

