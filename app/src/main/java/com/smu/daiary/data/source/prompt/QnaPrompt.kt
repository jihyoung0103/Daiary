  X: "오늘 날씨는 어떠셨나요?"                      (블럭에 이미 있는 내용)
  X: "고양시는 날씨가 흐렸는데 어떠셨나요?"           (도시 이름은 사용자에게 의미 없음)
-------------------------------------------------------------------------------
[스크린샷 처리]
