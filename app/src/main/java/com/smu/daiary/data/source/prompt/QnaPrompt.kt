package com.smu.daiary.data.source.prompt

/**
 * 질의응답 프롬프트. 실행되는 순서대로 적어 둔다.
 *
 *   1. [contextQuestionsPrompt] 소재마다 첫 질문을 한꺼번에 만든다
 *   2. [followUpQuestionPrompt] 답변을 받아 한 걸음 더 들어간다
 *
 * 둘이 공유하는 질문 작성 규칙은 [QUESTION_RULES] 하나로 두고 양쪽에 끼워 넣는다.
 *
 * 사이에 "카드에 도착한 시점에 그동안의 답변으로 첫 질문을 손보는" 단계가 있었는데
 * 걷어냈다. 이틀치 로그에서 손댄 5건 중 4건이 나빠졌다. "이 요리는 뭐예요?"를
 * "어디서 먹으셨어요?"로 바꿔 정체를 영영 못 묻게 하고, 갱신이 지운 질문을 후속이
 * 도로 묻는 식이었다. 첫 질문은 전체 블럭을 함께 보고 만드는데 갱신은 한 소재만 보니
 * 정보가 더 적었고, 규칙을 전부 넘겨줘도 마찬가지였다. 되살릴 거면 git 로그 참고.
 */

/**
 * 두 단계가 공유하는 질문 작성 규칙.
 * 단계마다 따로 적어 두면 한쪽만 고쳐서 규칙이 어긋난다. 여기만 고치면 둘이 함께 따라온다.
 */
private val QUESTION_RULES = """
- 반드시 열린 질문. "무엇 / 어떤 / 어디서 / 어떻게 / 누구"로 물으면 대개 열린 질문이 돼.
  "~인가요?", "~하셨나요?", "~맞나요?", "~있었어요?"로 끝나면 예/아니오로 닫히니 다시 써.
  "이유가 있었어요?"가 아니라 "이유가 뭐예요?"로 물어.
- 보기를 좁혀 주지 마. 고를 답을 네가 미리 만들어 주는 것도 닫힌 질문이야.
  X: "직접 만드신 건가요, 아니면 사오신 건가요?"
  X: "집에서 드셨나요, 밖에서 드셨나요?"
- 답을 정해놓고 확인받지 마. 빗나가면 사용자는 자기 하루를 말하는 대신 네 오해부터 해명하게 돼.
