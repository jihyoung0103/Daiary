package com.smu.daiary.data.source.prompt

/**
 * 질의응답 3단계 프롬프트. 실행되는 순서대로 적어 둔다.
 *
 *   1. [contextQuestionsPrompt] 소재마다 첫 질문을 한꺼번에 만든다
 *   2. [reviseQuestionPrompt]   카드에 도착한 시점에 그 사이 나온 답변으로 손본다
 *   3. [followUpQuestionPrompt] 답변을 받아 한 걸음 더 들어간다
 *
 * 셋은 규칙을 공유한다 — 열린 질문, 한 소재만 다루기, 존댓말 한 문장, 되묻기 금지.
 * 파일을 나눠 뒀더니 한쪽만 고쳐서 규칙이 어긋나는 일이 생겨 도로 붙였다.
 * 한 단계를 고칠 때 나머지 둘의 같은 규칙도 함께 봐야 한다.
 */

/**
 * 대화의 첫 질문을 만든다.
 * 깊이는 후속 질문이 만든다. 첫 질문의 역할은 후속이 붙잡을 구체적인 사실 하나를 끌어내는 것이라,
 * 이유·감정은 일부러 묻지 않고 '구체화'에만 집중시킨다.
 *
 * 여기 도달하는 블럭은 결제·사진·건강·날씨 넷뿐이다(WriteViewModel의 NO_QUESTION_TYPES가
 * 나머지를 거른다). 일정은 첫 질문이 고정이라 이 프롬프트를 타지 않는다.
 */
internal fun contextQuestionsPrompt(blocksText: String): String = """
오늘 하루의 데이터 블럭을 보고 사용자에게 물어볼 질문을 만들어.

일기의 알맹이는 사실이 아니라 그날 느끼고 판단한 것이야. 데이터에는 사실만 있으니
그건 네 질문으로만 끌어낼 수 있어. 다만 감정부터 물으면 "그냥 좋았어"로 끝나서,
첫 질문은 대개 사실을 물어 후속 질문이 붙잡을 발판을 만들어. 사실은 목적지가 아니라 발판이야.
블럭에 이미 사실이 충분하면(상세한 사진 분석처럼) 첫 질문부터 평가·감정을 물어도 돼.
후속 없이 끝날 수도 있으니, 한 번만 물을 수 있다면 무엇을 물어야 일기가 살아날지로 골라.

[무엇을 묻나]
데이터에는 "무슨 일이 있었는지"만 있고 "그게 무엇이었는지"가 없어. 그 빈칸을 물어.
- 결제: 금액과 가맹점은 있지만 무엇을 샀는지 없음
- 사진: 보이는 사물은 있지만 누구와 어디서인지 없음
- 건강: 걸음 수는 있지만 왜 그렇게 움직였는지 없음 (아래 판단 절차를 따라)
- 날씨: 빈칸이 아예 없음. 기온·습도·도시 이름은 데이터가 이미 다 갖고 있어.
  데이터에 없는 건 단 하나, 그 날씨가 사용자에게 어떻게 작용했는가야. 그것만 물어.
  O: "32도 더위가 오늘 하루에 어떤 영향을 줬나요?"
  X: "오늘 날씨는 어떠셨나요?"              (블럭에 이미 있는 내용)
  X: "고양시는 날씨가 흐렸는데 어떠셨나요?"   (도시 이름은 사용자에게 의미 없음)

[걸음 수 판단 절차]
걸음 수는 "18,432보 · 평소 5,200보"처럼 주어져. 뒤의 "평소"는 지난 7일의 중앙값이야.
숫자 자체는 사용자가 이미 알아. 평소와 얼마나 다른지만이 물을 거리야.

- "평소" 값이 없으면 건너뛰어. 비교할 기준이 없으면 물을 것도 없어.
- 평소의 1.5배를 넘는 날만 물어. 반드시 뭔가 있었던 날이고, 그 이유는 데이터에 없어.
  O: "오늘 18,432보를 걸으셨는데, 어디를 다녀오셨어요?"
  단, 같은 날 다른 블럭에 이유가 이미 있으면(일정에 "등산", 사진에 등산로) 건너뛰어.
  걸음 수는 다른 소스와 달리 그 사건들의 '결과'라, 원인이 적혀 있으면 빈칸이 없어.
- 평소의 절반 아래인 날은 묻지 마. 집에 있었는지, 폰을 두고 나갔는지, 차로 다녔는지
  구분할 수가 없어서 질문이 헛다리를 짚어. 적게 걸었다는 사실 자체도 일기에 쓸 게 없고.
  예외 — 그날 사진도 결제도 없으면 하루가 통째로 비니까, 그때만 하루의 모양을 물어.
- 그 사이면 건너뛰어. "평소처럼 다녔어" 말고 나올 답이 없어.
- 하루의 성격을 단정하지 마. 숫자만 제시하고 판단은 사용자가 하게 둬.
  X: "18,432보나 걸으신 활동적인 날인데, 뭐 하셨어요?"
  X: "6,328보로 많이 움직이지 않으신 날인데, 어디서 시간을 보내셨나요?"
     (하루종일 서서 일했는데 폰을 두고 있었을 수도 있어. 사용자가 해명부터 하게 된다)

content가 "[화면 캡처/수신 이미지]"로 시작하는 사진은 화면 내용이 분석에 이미 다 있어.
구체화할 게 없으니 "왜 이 화면을 남겼는지"만 물어. 화면 속 내용을 되묻지 마.
  O: "이 화면은 어떤 순간이라 남겨두신 거예요?"   X: "보스 소환은 무엇인가요?"

블럭마다 묻는 것이 다르니 중복은 걱정하지 마. "다른 블럭에서 나올 것 같다",
"사진에 이미 보인다"는 이유로 건너뛰지 마. 시각이 다르면 다른 일이고, 두 블럭이 같은 일이라는
근거는 어디에도 없어. 사용자가 그 얘기를 할지도 알 수 없고, 안 하면 그 정보는 영영 없는 거야.
걸음 수만 예외야 — 위 판단 절차를 따라. 걸음은 사건이 아니라 사건의 결과라서 그래.

[어떻게 묻나]
- 반드시 열린 질문. "무엇 / 어떤 / 어디서 / 어떻게 / 누구"로 물으면 대개 열린 질문이 돼.
  "~인가요?", "~하셨나요?", "~맞나요?", "~있었어요?"로 끝나면 예/아니오로 닫히니 다시 써.
  "이유가 있었어요?"가 아니라 "이유가 뭐예요?"로 물어.
  X: "집에서 드셨나요, 밖에서 드셨나요?"     (보기를 좁혀 주는 것도 닫힌 질문이야)
- 답을 미리 정해두고 확인받지 마. 빗나가면 사용자가 해명부터 해야 하고, 그건 대화가 아니야.
  O: "비 오는 하루를 어디서 보내셨나요?"     X: "비가 와서 집에 계셨겠어요, 맞나요?"
- 그 블럭 안의 사실을 하나만 질문에 넣어. 그래야 바로 떠올려서 답해.
  O: "14,200원은 무엇을 시키신 건가요?"
  X: "오늘 뭐 드셨나요?"                    (어느 블럭 얘긴지 알 수 없음)
  X: "17:15에 우아한형제들에서 24,000원은 무엇을 주문하신 건가요?"   (나열)
- 다른 블럭의 정보를 끌어와 섞지 마.
  X: 사진 블럭을 물으면서 결제 블럭의 가맹점 이름을 넣기
- [추측]에 있는 이름을 사실처럼 넣지 마. 대신 그 이름 자체를 물어.
  사용자가 답해주면 그게 확실한 사실이 돼.
  O: "이 치킨은 어디서 시키신 건가요?"      X: "올레 치킨은 어디서 시키신 건가요?"
- 한 번에 두 가지를 묻지 마.                X: "어디서 누구와 드셨나요?"
- 곱씹어야 답이 나오는 걸 묻지 마.
  O: "회의에서 어떤 이야기가 오갔나요?"     X: "회의는 어떤 의미였나요?"
- "어떠셨나요?", "좋으셨나요?" 같은 되묻기는 사용자가 이미 아는 걸 요약하게 만들 뿐이고,
  이어 물을 거리도 안 남아.
- 존댓말 한 문장. 사용자가 직접 타이핑하니 한두 문장으로 답할 수 있게.

[개수]
- 한 블럭당 최대 1개. 전체 개수 제한은 없어. 무엇을 답할지는 사용자가 고른다.
- 답변을 들어도 일기 문장이 하나도 늘지 않는 블럭, 블럭 내용에 이미 답이 적혀 있는 블럭은
  건너뛰어. 0개여도 괜찮아. 반대로 개수를 채우려고 억지 질문을 만들지도 마.

데이터 블럭:
$blocksText

반드시 아래 JSON 형식으로만 응답해. 다른 텍스트는 포함하지 마.
모든 블럭 id는 questions와 skipped 중 정확히 한 곳에 들어가야 해.
건너뛴 블럭은 빠뜨리지 말고 skipped에 넣고, 그 이유를 30자 이내로 적어.
{
  "questions": [
    { "blockId": "블럭 id", "question": "질문 텍스트" }
  ],
  "skipped": [
    { "blockId": "블럭 id", "reason": "질문을 만들지 않은 이유" }
  ]
}
""".trimIndent()

/**
 * 미리 만들어 둔 질문을 그 사이 나온 답변에 맞춰 손본다.
 *
 * 첫 질문들은 대화가 시작되기 전에 한꺼번에 만들어지므로, 중간에 사용자가 답한 내용이
 * 반영돼 있지 않다. 그래서 이미 답이 나온 걸 또 묻거나, 답변 덕에 가능해진 더 좋은 질문을
 * 놓친다. 카드에 도착하는 시점에 이 프롬프트로 한 번 손본다.
 */
internal fun reviseQuestionPrompt(
    sourceId: String,
    sourceLabel: String,
    sourceContent: String,
    question: String,
    priorAnswers: String
): String = """
사용자와 하루에 대해 대화하는 중이야.
아래 질문은 대화를 시작하기 전에 미리 만들어 둔 거라, 그 사이 사용자가 한 답변이 반영돼 있지 않아.
지금까지의 답변을 보고 이 질문을 손봐줘.

[지금 손볼 소재]
$sourceLabel · $sourceId
$sourceContent

[미리 만들어 둔 질문]
$question

[지금까지 사용자가 답한 것]
소재별로 묶여 있어. 대괄호가 소재 구분이고, 한 묶음 안의 Q/A는 그 소재를 두고 이어간 대화야.
다른 소재에서 나온 답을 이 소재의 일과 같은 일로 여기지 마.

$priorAnswers

[어떻게 판단하나]
- 고칠 이유가 없으면 원래 질문을 그대로 돌려줘. 이게 기본이야. 멀쩡한 질문을 다듬지 마.
- 답변 덕분에 더 나은 질문이 가능해졌으면 그걸로 바꿔.
  예: 앞에서 "저녁을 못 먹었다"는 답이 나왔다면, 야식 사진은 그 사실을 이어받아 물을 수 있어.
- 이미 답이 나온 것을 묻고 있으면, 이 소재에서 아직 안 나온 것을 묻는 질문으로 바꿔.
- 이 소재에 대해 더 물을 것이 남아 있지 않으면 빈 문자열로 응답해. 그 카드는 건너뛴다.

[고칠 때 지켜야 할 것]
- 질문의 대상은 바꾸지 마. 반드시 [지금 손볼 소재]의 데이터를 묻는 질문이어야 해.
- 원래 질문에 그 소재의 사실(금액, 걸음 수, 시각 등)이 들어 있었다면 그대로 남겨.
  그게 사라지면 사용자는 무엇에 대한 질문인지 알 수 없게 돼.
  X: "2,993보로 많이 움직이지 않으셨는데 어디서 시간을 보내셨나요?"
     → "에어컨을 틀고 집에서 주로 뭘 하셨어요?"
     (걸음 수가 사라졌고, 날씨 답변을 그대로 옮겨와 날씨 질문과 같아짐)
- 다른 소재에서 이미 물은 것과 비슷해질 것 같으면, 고치지 말고 빈 문자열로 응답해.
  비슷한 질문을 두 번 하느니 그 카드를 건너뛰는 게 나아.

질문 작성 규칙은 원래와 같아.
- 열린 질문. "~인가요?", "~하셨나요?"로 끝나면 예/아니오로 닫히니 다시 써.
- 존댓말 한 문장. 한두 문장으로 답할 수 있게.
- 한 번에 두 가지를 묻지 마.
- 다른 소재의 정보를 이 질문에 끌어오지 마.

반드시 아래 JSON 형식으로만 응답해. 다른 텍스트는 포함하지 마:
{ "question": "질문 또는 빈 문자열" }
""".trimIndent()

/**
 * 방금 받은 답변을 근거로 한 걸음 더 들어가는 후속 질문을 만든다.
 *
 * 첫 질문이 '무엇'을 물어 구체적인 사실을 끌어냈다면, 후속은 그 사실을 붙잡고
 * '왜/어땠는지'로 들어간다. 데이터에 절대 남지 않는 정보가 여기서 나온다.
 * 더 물을 게 없으면 빈 문자열을 돌려받아 카드를 넘긴다.
 */
internal fun followUpQuestionPrompt(
    sourceContent: String,
    conversation: String
): String = """
사용자와 한 소재를 두고 대화하는 중이야. 지금까지 주고받은 걸 보고 한 번 더 물어봐.

첫 질문이 사실을 끌어냈으니, 이제 그 사실을 붙잡고 일기의 알맹이로 들어갈 차례야.
맛이 어땠는지, 왜 그랬는지, 누구와 있었는지, 그때 어떤 기분이었는지 —
데이터에는 절대 남지 않고 본인만 아는 것들이야. 그게 없으면 일기가 아니라 기록이 돼.

[원래 데이터]
$sourceContent

[지금까지 주고받은 것]
$conversation

[어떻게 묻나]
- 이 소재를 벗어나지 마. [원래 데이터]가 무엇에 대한 것인지 보고 그 범위 안에서만 물어.
  답변이 다른 일로 흘러갔다면 그건 그 일을 다루는 다른 카드의 몫이야.
  여기서 따라가면 답변이 엉뚱한 소재에 저장돼 일기 문단이 어긋나.
  이 소재로 더 물을 게 없으면 그만 물어(빈 문자열).
  X: 걸음 수 카드에서 "뷔페에서 뭘 드셨어요?"      (음식은 음식 카드의 몫)
  X: 날씨 카드에서 "그 영화 재밌었어요?"           (영화는 날씨 소재가 아님)
- 사용자가 답에 쓴 단어를 골라서 그걸 물어. 단, 이 소재와 이어지는 단어여야 해.
  상대가 꺼낸 말에 반응해야 대화가 되지만, 아무 단어나 붙잡으면 주제가 새.
- 반드시 열린 질문으로 물어. 사용자가 자유롭게 떠올려 답할 수 있어야 해.
  "무엇 / 어떤 / 어떻게 / 왜 / 얼마나 / 누구"로 묻으면 대개 열린 질문이 된다.
  "~인가요?", "~하셨나요?", "~맞나요?", "~있었어요?", "~있나요?"로 끝나면
  예/아니오로 닫히니 다시 써. "이유가 있었어요?"가 아니라 "이유가 뭐예요?"로 물어.
- 아래 축 중에서 사용자가 답변에서 아직 말하지 않은 것을 하나 골라 한 걸음 들어가.
  답변이 이미 채운 축은 다시 묻지 마. 예를 들어 "할인해줘서 시켰어"라고 답했다면
  이유를 이미 말한 것이니 동기 대신 다른 축을 골라.
  비어 있는 축이 여럿이면 동기를 우선해. 데이터에 가장 남지 않는 정보라서 그래.
  **직전 질문과 같은 축을 연달아 쓰지 마.** 기분을 물었으면 다음은 기분 말고 다른 축이야.
  쓸 축이 남지 않았으면 그만 물어(빈 문자열). 같은 걸 표현만 바꿔 또 묻는 것보다 낫다.
  X: "그때 기분이 어땠어요?" 다음에 "그 순간이 어떻게 느껴졌어요?"   (둘 다 감정)
  동기 — 왜 그렇게 했는지
    O: "오늘 이걸 고르신 이유가 뭐예요?"     X: "오늘따라 시키신 이유가 있나요?"
  평가 — 좋았는지 별로였는지, 다음에도 그럴 건지
    O: "다시 시킨다면 무엇을 바꾸고 싶으세요?"
    O: "먹어보니 어떤 점이 제일 기억에 남으세요?"
  사람 — 누구와 함께였는지, 무슨 얘기를 나눴는지
    함께 있었을 법한 소재에만 써. 혼자 하는 일(게임, 혼밥, 산책)에는 묻지 마.
    답변에 이미 누군가 등장했다면 그 사람에 대해 물어. 없던 사람을 찾아내려 하지 마.
    O: "그때 무슨 얘기를 나누셨어요?"          (답변에 친구가 나온 뒤)
    X: "게임하실 때 주변에 누가 있었어요?"     (혼자 하는 일)
  기대 — 예상과 무엇이 달랐는지
    O: "생각하던 것과 어떻게 달랐나요?"      X: "생각하신 만큼이던가요?"
  변화 — 얼마나 자주 있는 일인지
    O: "얼마나 자주 가시는 곳이에요?"        X: "자주 가시는 곳인가요?"
  감정 — 그때 기분
    O: "다 드시고 나서 어떤 기분이 드셨나요?"
  몸 — 몸이 어땠는지. 걸음 수·운동처럼 몸을 쓴 소재에만 써.
    걸음 수 카드는 이 축으로 마무리해. 다른 소재는 몸 얘기를 못 하니까
    이 축이 걸음 수 블럭만 낼 수 있는 유일한 문장이야.
    O: "그만큼 걷고 나니 몸은 어땠어요?"      X: "결제하시고 몸은 괜찮으셨어요?"

  '평가'를 특히 눈여겨봐. 좋았는지 별로였는지는 어떤 데이터에도 남지 않으면서
  일기에서는 가장 중요한 부분이야.

  같은 표현으로 시작하는 질문을 연달아 던지지 마.
  X: "그 픽업을 뽑았을 때 어떤 기분이었어요?" 다음에 "그 픽업을 뽑았을 때 누가 있었어요?"
