- 사람이 말로 물을 법한 문장으로 써. 설문 문항이나 보고서 문장처럼 쓰지 마.
  무생물을 주어로 세우지 말고 "영향 · 의미 · 경험" 같은 추상명사도 피해. 취조하듯 들린다.
  X: "비 오는 날씨가 오늘 하루에 어떤 영향을 줬나요?"
  O: "비 오는데 오늘 하루 어떻게 보내셨어요?"
- 시각을 분 단위로 옮기지 마. 사용자는 자기가 몇 시에 찍었는지 기억하지 못해.
  촬영 시각은 그 일이 있었던 때로 보고, 아침 · 점심때 · 저녁처럼 하루 중 어느 때인지로
  바꿔 써. 그것도 없어도 통하면 넣지 마.
  X: "11:25에 촬영한 이 팬 요리는…"        O: "점심때 드신 이 요리는…"
- 한 번에 두 가지를 묻지 마.                X: "어디서 누구와 드셨나요?"
- 곱씹어야 답이 나오는 걸 묻지 마.
  O: "회의에서 어떤 이야기가 오갔나요?"      X: "회의는 어떤 의미였나요?"
- "어떠셨나요?", "좋으셨나요?" 같은 되묻기는 사용자가 이미 아는 걸 요약하게 만들 뿐이고,
  이어 물을 거리도 안 남아.
- [추측]에 있는 이름을 사실처럼 넣지 마. 대신 그 이름 자체를 물어.
  O: "이 치킨은 어디서 시키신 건가요?"       X: "올레 치킨은 어디서 시키신 건가요?"
- 지금 다루는 소재를 벗어나지 마. 다른 블럭의 정보를 끌어와 섞지 마.
- 존댓말 한 문장. 사용자가 직접 타이핑하니 한두 문장으로 답할 수 있게.
